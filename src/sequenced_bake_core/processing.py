def clear_generated_textures(props, images=None):
    """Remove only images generated by the current bake operation.

    Args:
        props: Sequenced Bake property group.
        images: Optional iterable of images created by the operation.
    """
    if not props.sequence_clear_baked_maps or not images:
        return

    for image in list(images):
        if image is not None:
            try:
                bpy.data.images.remove(image)
            except (ReferenceError, RuntimeError) as exc:
                print(f"[Sequenced Bake] Failed to remove generated image '{getattr(image, 'name', '<unknown>')}': {exc}")


def _find_principled_and_output(material):
    """Return the first Principled BSDF and active Material Output nodes."""
    nodes = material.node_tree.nodes
    bsdf = next((node for node in nodes if node.type == "BSDF_PRINCIPLED"), None)
    output = next(
        (
            node
            for node in nodes
            if node.type == "OUTPUT_MATERIAL" and getattr(node, "is_active_output", False)
        ),
        None,
    )
    if output is None:
        output = next((node for node in nodes if node.type == "OUTPUT_MATERIAL"), None)
    return bsdf, output


def connect_metallic_node(material):
    """Prepare a material for metallic baking and return restoration state.

    The metallic value is routed into an emission shader so the standard
    Cycles EMIT bake produces the scalar metallic signal as RGB.

    Args:
        material: Material whose node tree will be temporarily modified.

    Returns:
        dict: Exact output-surface links and temporary nodes for restoration.

    Raises:
        RuntimeError: If the material does not contain the required nodes.
    """
    nodes = material.node_tree.nodes
    links = material.node_tree.links
    bsdf, output = _find_principled_and_output(material)

    if not bsdf or not output:
        raise RuntimeError("Required nodes not found for metallic bake")

    state = {
        "surface_links": [(link.from_socket, link.to_socket) for link in output.inputs["Surface"].links],
        "temporary_nodes": [],
    }

    emission = nodes.new(type="ShaderNodeEmission")
    emission.label = TEMP_NODE_TAG
    emission.inputs["Strength"].default_value = 1.0

    if bsdf.inputs["Metallic"].is_linked:
        links.new(bsdf.inputs["Metallic"].links[0].from_socket, emission.inputs["Color"])
    else:
        value = float(bsdf.inputs["Metallic"].default_value)
        emission.inputs["Color"].default_value = (value, value, value, 1.0)

    for link in list(output.inputs["Surface"].links):
        links.remove(link)
    links.new(emission.outputs["Emission"], output.inputs["Surface"])
    state["temporary_nodes"] = [emission]
    return state


def connect_occlusion_node(material):
    """Prepare an ORM material and return exact restoration state.

    The generated shader emits ambient occlusion, roughness, and metallic
    values as RGB so the result can be baked into a single image.

    Args:
        material: Material whose node tree will be temporarily modified.

    Returns:
        dict: Temporary nodes and original output links.

    Raises:
        RuntimeError: If the material does not contain the required nodes.
    """
    nodes = material.node_tree.nodes
    links = material.node_tree.links
    bsdf, output = _find_principled_and_output(material)

    if not bsdf or not output:
        raise RuntimeError("Required nodes not found for occlusion bake")

    state = {
        "surface_links": [(link.from_socket, link.to_socket) for link in output.inputs["Surface"].links],
        "temporary_nodes": [],
    }

    combine = nodes.new(type="ShaderNodeCombineColor")
    combine.mode = "RGB"
    combine.label = TEMP_NODE_TAG

    ao = nodes.new(type="ShaderNodeAmbientOcclusion")
    ao.samples = 16
    ao.inputs["Color"].default_value = (1.0, 1.0, 1.0, 1.0)
    ao.label = TEMP_NODE_TAG

    temp_bsdf = nodes.new(type="ShaderNodeBsdfPrincipled")
    temp_bsdf.label = TEMP_NODE_TAG
    temp_bsdf.inputs["Base Color"].default_value = (0.0, 0.0, 0.0, 1.0)
    temp_bsdf.inputs["Roughness"].default_value = 1.0
    if "Emission Strength" in temp_bsdf.inputs:
        temp_bsdf.inputs["Emission Strength"].default_value = 1.0

    links.new(ao.outputs["Color"], combine.inputs["Red"])

    if bsdf.inputs["Metallic"].is_linked:
        links.new(bsdf.inputs["Metallic"].links[0].from_socket, combine.inputs["Green"])
    else:
        combine.inputs["Green"].default_value = bsdf.inputs["Metallic"].default_value

    if bsdf.inputs["Roughness"].is_linked:
        links.new(bsdf.inputs["Roughness"].links[0].from_socket, combine.inputs["Blue"])
    else:
        combine.inputs["Blue"].default_value = bsdf.inputs["Roughness"].default_value

    if "Alpha" in bsdf.inputs and "Alpha" in temp_bsdf.inputs:
        if bsdf.inputs["Alpha"].is_linked:
            links.new(bsdf.inputs["Alpha"].links[0].from_socket, temp_bsdf.inputs["Alpha"])
        else:
            temp_bsdf.inputs["Alpha"].default_value = bsdf.inputs["Alpha"].default_value

    if "Normal" in bsdf.inputs and "Normal" in temp_bsdf.inputs:
        if bsdf.inputs["Normal"].is_linked:
            links.new(bsdf.inputs["Normal"].links[0].from_socket, temp_bsdf.inputs["Normal"])

    links.new(combine.outputs["Color"], temp_bsdf.inputs["Emission Color"])

    for link in list(output.inputs["Surface"].links):
        links.remove(link)
    links.new(temp_bsdf.outputs["BSDF"], output.inputs["Surface"])

    state["temporary_nodes"] = [combine, ao, temp_bsdf]
    return state


def restore_material_state(material, state):
    """Restore a material's exact surface links and remove temporary nodes."""
    if not state:
        return

    nodes = material.node_tree.nodes
    links = material.node_tree.links
    _, output = _find_principled_and_output(material)

    if output:
        for link in list(output.inputs["Surface"].links):
            links.remove(link)

        for from_socket, to_socket in state.get("surface_links", []):
            try:
                links.new(from_socket, to_socket)
            except (ReferenceError, RuntimeError) as exc:
                print(f"[Sequenced Bake] Failed to restore material link: {exc}")

    for node in state.get("temporary_nodes", []):
        try:
            if node.name in nodes:
                nodes.remove(node)
        except (ReferenceError, RuntimeError) as exc:
            print(f"[Sequenced Bake] Failed to remove temporary node: {exc}")


def reconnect_node(material, state=None, temp_tag=TEMP_NODE_TAG):
    """Restore temporary material state.

    The state-aware path is preferred. The tag-based path remains available
    for compatibility with older callers.
    """
    if state is not None:
        restore_material_state(material, state)
        return

    nodes = material.node_tree.nodes
    for node in list(nodes):
        if node.label == temp_tag:
            nodes.remove(node)



def create_image_texture(
    material,
    name,
    width,
    height,
    alpha,
    float_buffer,
    interpolation,
    projection,
    extension,
    colorspace,
    file_format,
):
    """Create and activate an image texture node for baking.

    Returns:
        tuple: Created image texture node and image datablock.
    """
    image = bpy.data.images.new(
        name=name,
        width=width,
        height=height,
        alpha=alpha,
        float_buffer=float_buffer,
    )

    try:
        image.colorspace_settings.name = colorspace
    except (TypeError, ValueError) as exc:
        print(
            f"[Sequenced Bake] Could not set image color space '{colorspace}' "
            f"for '{image.name}': {exc}"
        )

    node_tree = material.node_tree
    node = node_tree.nodes.new("ShaderNodeTexImage")
    node.image = image
    node.interpolation = interpolation
    node.projection = projection.upper()
    node.extension = extension.upper()

    node_tree.nodes.active = node
    for existing in node_tree.nodes:
        existing.select = False
    node.select = True

    output = next(
        (item for item in node_tree.nodes if item.type == "OUTPUT_MATERIAL"),
        None,
    )
    if output:
        node.location = (output.location.x + 300, output.location.y)

    image.file_format = IMAGE_FORMAT_MAP.get(file_format, file_format)
    return node, image


def _configure_bake_pass(bake, bake_type, props):
    """Apply bake-pass-specific Cycles settings."""
    if bake_type == "DIFFUSE":
        bake.use_pass_direct = props.diffuse_lighting_direct
        bake.use_pass_indirect = props.diffuse_lighting_indirect
        bake.use_pass_color = props.diffuse_lighting_color
    elif bake_type == "GLOSSY":
        bake.use_pass_direct = props.glossy_lighting_direct
        bake.use_pass_indirect = props.glossy_lighting_indirect
        bake.use_pass_color = props.glossy_lighting_color
    elif bake_type == "TRANSMISSION":
        bake.use_pass_direct = props.transmission_lighting_direct
        bake.use_pass_indirect = props.transmission_lighting_indirect
        bake.use_pass_color = props.transmission_lighting_color
    elif bake_type == "COMBINED":
        bake.use_pass_direct = props.combined_lighting_direct
        bake.use_pass_indirect = props.combined_lighting_indirect
        bake.use_pass_diffuse = props.combined_contribution_diffuse
        bake.use_pass_glossy = props.combined_contribution_glossy
        bake.use_pass_transmission = props.combined_contribution_transmission
        bake.use_pass_emit = props.combined_contribution_emit
    elif bake_type == "NORMAL":
        bake.normal_space = props.normal_map_space
        bake.normal_r = props.normal_map_red_channel
        bake.normal_g = props.normal_map_green_channel
        bake.normal_b = props.normal_map_blue_channel


def _apply_color_management(scene, props):
    """Apply configured color-management values with console diagnostics."""
    assignments = (
        (scene.display_settings, "display_device", props.display_device),
        (scene.view_settings, "view_transform", props.view_transform),
        (scene.view_settings, "look", props.look),
    )
    for target, attribute, value in assignments:
        try:
            setattr(target, attribute, value)
        except (TypeError, ValueError, RuntimeError) as exc:
            print(f"[Sequenced Bake] Could not set {attribute}='{value}': {exc}")

    scene.view_settings.exposure = props.exposure
    scene.view_settings.gamma = props.gamma

    try:
        scene.sequencer_colorspace_settings.name = props.sequencer
    except (TypeError, ValueError, RuntimeError) as exc:
        print(f"[Sequenced Bake] Could not set sequencer color space '{props.sequencer}': {exc}")


def _save_image(image, output_dir, frame, file_format):
    """Save an image using its explicitly configured Blender file format."""
    os.makedirs(output_dir, exist_ok=True)
    blender_format = IMAGE_FORMAT_MAP.get(file_format, file_format)
    image.file_format = blender_format
    extension = file_format.lower()
    if extension in {"openexr", "exr"}:
        extension = "exr"
    filepath = os.path.join(output_dir, f"{frame}.{extension}")
    image.filepath_raw = filepath
    image.save()
    return filepath


def bake_frame(
    bake_type,
    props,
    frame,
    obj,
    mat,
    image_node,
    image,
    output_dir,
    sculpt_bounds=None,
):
    """Bake and save one frame for a material and bake pass."""
    scene = bpy.context.scene
    bake = scene.render.bake
    _configure_bake_pass(bake, bake_type, props)
    _apply_color_management(scene, props)

    cage_name = (
        props.selected_to_active_cage_object.name
        if props.selected_to_active_cage and props.selected_to_active_cage_object
        else ""
    )

    try:
        if bake_type == "SCULPT":
            bounds_obj = props.sequenced_bake_sculpt_bounds_object
            if sculpt_bounds is None:
                sculpt_bounds = calculate_sculpt_bounds(obj, bounds_obj=bounds_obj)

            bake_sculpt_direct_to_buffer(obj, image, sculpt_bounds, bounds_obj=bounds_obj)
            filepath = _save_image(
                image,
                output_dir,
                frame,
                props.sequenced_bake_image_format,
            )
        else:
            bpy.ops.object.bake(
                type="EMIT" if bake_type in {"METALLIC", "OCCLUSION"} else bake_type,
                use_selected_to_active=props.sequenced_selected_to_active,
                max_ray_distance=(
                    0.0 if props.selected_to_active_cage else props.selected_to_active_max_ray_distance
                ),
                cage_extrusion=props.selected_to_active_extrusion,
                cage_object=cage_name,
                use_cage=props.selected_to_active_cage,
            )
            filepath = _save_image(
                image,
                output_dir,
                frame,
                props.sequenced_bake_image_format,
            )

        print(f"[Sequenced Bake] Saved {bake_type} frame {frame}: {filepath}")
        return filepath
    except Exception as exc:
        mat_name = mat.name if mat else "None"
        print(
            f"[Sequenced Bake] Bake failed - material='{mat_name}', "
            f"type='{bake_type}', frame={frame}: {exc}"
        )
        raise